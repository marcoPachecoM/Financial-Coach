-- Recurring transactions: a rule ("Netflix, 199.00, every month") from which the application
-- creates the next occurrences automatically. Every transaction of a rule points to it and
-- says which occurrence (due date) it covers.

CREATE TABLE recurring_transactions (
    id             uuid           PRIMARY KEY DEFAULT uuidv7(),
    user_id        uuid           NOT NULL,
    account_id     uuid           NOT NULL,
    type           varchar(10)    NOT NULL,
    name           varchar(255)   NOT NULL,
    amount         numeric(14, 2) NOT NULL,
    category_group varchar(50)    NOT NULL,
    category       varchar(100),
    notes          varchar(1000),
    frequency      varchar(10)    NOT NULL,
    start_date     date           NOT NULL,
    time_of_day    time           NOT NULL,
    end_date       date,
    next_due_date  date,
    created_at     timestamptz    NOT NULL DEFAULT now(),
    updated_at     timestamptz    NOT NULL DEFAULT now(),

    -- Same ownership rule as transactions: the rule's user owns its account.
    CONSTRAINT fk_recurring_transactions_account FOREIGN KEY (account_id, user_id)
        REFERENCES accounts (id, user_id) ON DELETE CASCADE,
    CONSTRAINT fk_recurring_transactions_category_group FOREIGN KEY (category_group)
        REFERENCES category_groups (name) ON UPDATE CASCADE,
    -- Target of the composite foreign key from transactions (same rule, same account).
    CONSTRAINT ux_recurring_transactions_id_account UNIQUE (id, account_id),
    CONSTRAINT ck_recurring_transactions_type CHECK (type IN ('EXPENSE', 'INCOME')),
    CONSTRAINT ck_recurring_transactions_amount_sign
        CHECK ((type = 'EXPENSE' AND amount > 0) OR (type = 'INCOME' AND amount < 0)),
    CONSTRAINT ck_recurring_transactions_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_recurring_transactions_frequency CHECK (frequency IN ('WEEKLY', 'BIWEEKLY', 'MONTHLY', 'YEARLY')),
    CONSTRAINT ck_recurring_transactions_end_date CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT ck_recurring_transactions_next_due_date CHECK (next_due_date IS NULL OR next_due_date > start_date)
);

-- The generator looks for rules with an occurrence due.
CREATE INDEX ix_recurring_transactions_next_due_date
    ON recurring_transactions (next_due_date)
    WHERE next_due_date IS NOT NULL;
CREATE INDEX ix_recurring_transactions_account_user ON recurring_transactions (account_id, user_id);

COMMENT ON TABLE recurring_transactions IS 'Rules that create the next occurrences of a transaction automatically.';
COMMENT ON COLUMN recurring_transactions.amount IS 'Expected amount, signed like transactions.amount. Generated occurrences use it.';
COMMENT ON COLUMN recurring_transactions.start_date IS 'Due date of occurrence 0 (the original transaction); every due date is computed from it.';
COMMENT ON COLUMN recurring_transactions.time_of_day IS 'Local time given to the generated transactions.';
COMMENT ON COLUMN recurring_transactions.end_date IS 'Last day an occurrence may fall on. NULL: no end. Setting it stops the rule.';
COMMENT ON COLUMN recurring_transactions.next_due_date IS 'Next occurrence to create. NULL when the rule has ended.';

ALTER TABLE transactions
    ADD COLUMN recurring_transaction_id uuid,
    ADD COLUMN recurrence_date          date,
    -- Both or neither: a linked transaction always says which occurrence it covers.
    ADD CONSTRAINT ck_transactions_recurrence
        CHECK ((recurring_transaction_id IS NULL) = (recurrence_date IS NULL)),
    -- Composite key: a transaction can only belong to a rule of its own account.
    -- NO ACTION: the application unlinks the transactions before deleting a rule; deleting an
    -- account removes both tables in the same statement.
    ADD CONSTRAINT fk_transactions_recurring_transaction FOREIGN KEY (recurring_transaction_id, account_id)
        REFERENCES recurring_transactions (id, account_id);

ALTER TABLE transactions DROP CONSTRAINT ck_transactions_source;
ALTER TABLE transactions
    ADD CONSTRAINT ck_transactions_source CHECK (source IN ('MANUAL', 'CSV', 'RECURRING'));

-- At most one active transaction per occurrence. Deleted rows are excluded, so a real charge
-- from a CSV can replace the generated one (which is soft-deleted).
CREATE UNIQUE INDEX ux_transactions_recurrence
    ON transactions (recurring_transaction_id, recurrence_date)
    WHERE deleted_at IS NULL AND recurring_transaction_id IS NOT NULL;

COMMENT ON COLUMN transactions.source IS 'Channel that created the row: MANUAL, CSV or RECURRING (generated by a rule). Internal.';
COMMENT ON COLUMN transactions.recurring_transaction_id IS 'Rule this transaction is an occurrence of. NULL: not recurring.';
COMMENT ON COLUMN transactions.recurrence_date IS 'Due date of the occurrence this transaction covers (may differ from datetime by a few days).';
